using WildernessGameplay;
using UnityEngine;

// Creates the board, stores each tile's data, and places the player.
// Only procedural tiles are instantiated. The player and camera are scene objects.
public class BoardManager : MonoBehaviour
{
    [Header("Tile Prefabs: Plains, Forest, Desert, Swamp, Mountain")]
    public GameObject[] tilePrefabs;
    [Header("Player")]
    public GameObject player;
    public float playerXOffset = .9f;
    public float playerYPosition = 0f;
    [Header("Board Organization")]
    public Transform boardParent;
    public BoardCamera boardCamera;
    [Header("Tile Size")]
    public float tileWidth = 5.11f;
    public float tileHeight = 5.11f;
    [Header("Difficulty When Opening Game Scene Directly")]
    public DifficultyLevel directStartDifficulty = DifficultyLevel.Easy;
    public int BoardWidth { get; private set; }
    public int BoardHeight { get; private set; }
    public Transform PlayerTransform => player == null || !player.activeSelf ? null : player.transform;
    public bool OverviewActive { get; private set; }

    // Stores tile views using the original tileDataGrid[x, y] coordinates.
    private TileData[,] tileDataGrid;
    private Game session;

    // Initializes the board using the settings created by GameManager.
    private void Start()
    {
        var manager = GameManager.EnsureInstance();
        if (manager.settings == null && !manager.Configure(directStartDifficulty, Random.Range(0, int.MaxValue))) return;
        if (player == null || boardParent == null || boardCamera == null || tileWidth <= 0 || tileHeight <= 0 ||
            tilePrefabs == null || tilePrefabs.Length != 5)
        {
            Debug.LogError("Assign the scene player, board parent, camera, five tile prefabs, and positive tile sizes.", this);
            return;
        }
        foreach (var prefab in tilePrefabs)
        {
            if (prefab == null || prefab.GetComponent<TileData>() == null)
            {
                Debug.LogError("Each terrain prefab needs a TileData component.", this);
                return;
            }
        }

        OverviewActive = boardCamera.isActiveAndEnabled;
        manager.BeginBoard(this);
        session = manager.Session;
        BoardWidth = session.Rules.boardWidth;
        BoardHeight = session.Rules.boardHeight;
        SpawnBoard(BoardWidth, BoardHeight);
        PlacePlayer();
        RefreshViews();
    }

    // Creates every tile and connects its view to the resources already generated by Map.
    private void SpawnBoard(int width, int height)
    {
        tileDataGrid = new TileData[width, height];
        for (int x = 0; x < width; x++)
        {
            for (int y = 0; y < height; y++)
            {
                var state = session.Tiles[x, y];
                GameObject tilePrefab = tilePrefabs[(int)state.Terrain];
                Vector3 spawnPosition = new Vector3(x * tileWidth, y * tileHeight, 0);
                GameObject spawnedTile = Instantiate(tilePrefab, spawnPosition, Quaternion.identity, boardParent);
                TileData tileData = spawnedTile.GetComponent<TileData>();
                tileData.Initialize(state, x == width - 1);
                tileDataGrid[x, y] = tileData;
            }
        }
    }

    // Replaces the original SpawnPlayer: enable the pre-placed player at its generated starting square.
    private void PlacePlayer()
    {
        player.transform.position = WorldPosition(session.Player.X, session.Player.Y);
        player.SetActive(true);
    }

    // Convert grid coordinates into world coordinates, retaining the small rightward sprite offset.
    private Vector3 WorldPosition(int x, int y) => new Vector3(x * tileWidth + playerXOffset, y * tileHeight + playerYPosition, 0);

    // Update tokens and visibility after a game action; this never regenerates tile data.
    public void RefreshViews()
    {
        if (session == null || tileDataGrid == null) return;
        foreach (var tileData in tileDataGrid)
        {
            var square = tileData.State;
            tileData.RefreshVisuals();
            tileData.SetVisibility(OverviewActive || session.Visible[square.X, square.Y]);
        }
        player.transform.position = WorldPosition(session.Player.X, session.Player.Y);
    }

    // BoardCamera calls this after its overview/zoom, enabling terrain-based visibility.
    public void FinishOverview()
    {
        if (!OverviewActive) return;
        OverviewActive = false;
        RefreshViews();
        GameManager.Instance.FinishOverview();
    }

    // Returns the TileData at the requested grid position, or null outside the board.
    public TileData GetTileData(int x, int y) => tileDataGrid != null && x >= 0 && y >= 0 && x < BoardWidth && y < BoardHeight ? tileDataGrid[x, y] : null;
}
