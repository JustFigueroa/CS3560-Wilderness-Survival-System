using WildernessGameplay;
using UnityEngine;

// Scene view of one authoritative tile. Refreshing never rerolls resources.
public class TileData : MonoBehaviour
{
    [Header("Available Resource Tokens")]
    public GameObject[] availableFoodTokens;
    public GameObject[] availableWaterTokens;
    public GameObject[] availableGoldTokens;
    [Header("Resource Cost Tokens")]
    public GameObject[] costFoodTokens;
    public GameObject[] costWaterTokens;
    // Resource values come from the model; retain the original available/cost amount names for callers.
    public Square State { get; private set; }
    public int availableFoodAmount => State?.Food ?? 0;
    public int availableWaterAmount => State?.Water ?? 0;
    public int availableGoldAmount => State?.Gold ?? 0;
    public int costFoodAmount => State?.FoodCost ?? 0;
    public int costWaterAmount => State?.WaterCost ?? 0;

    private SpriteRenderer[] sprites;
    [SerializeField] private GameObject traderMarker;
    [SerializeField] private GameObject finishMarker;
    private MeshRenderer[] labels;
    // Bind the square generated by Map. This replaces GenerateResources, which formerly rolled values here.
    public void Initialize(Square state, bool isFinishTile)
    {
        State = state;
        if (finishMarker != null) finishMarker.SetActive(isFinishTile);
        labels = GetComponentsInChildren<MeshRenderer>(true);
        sprites = GetComponentsInChildren<SpriteRenderer>(true);
        RefreshVisuals();
    }

    // Update the prepared resource tokens and trader marker to match the current model values.
    public void RefreshVisuals()
    {
        if (State == null)
        {
            return;
        }

        if (traderMarker != null) traderMarker.SetActive(State.Trader != null);
        ActivateTokens(availableFoodTokens, State.Food);
        ActivateTokens(availableWaterTokens, State.Water);
        ActivateTokens(availableGoldTokens, State.Gold);
        ActivateTokens(costFoodTokens, State.FoodCost);
        ActivateTokens(costWaterTokens, State.WaterCost);
    }

    // Enable the first amount token objects and disable the rest, as in the original TileData.
    private static void ActivateTokens(GameObject[] tokens, int amount)
    {
        if (tokens == null)
        {
            return;
        }

        for (int i = 0; i < tokens.Length; i++)
        {
            if (tokens[i] != null)
            {
                tokens[i].SetActive(i < amount);
            }
        }
    }

    // Hide or show the existing renderers, including inactive token children; do not recreate objects.
    public void SetVisibility(bool visible)
    {
        if (sprites == null)
        {
            return;
        }

        for (int i = 0; i < sprites.Length; i++)
        {
            sprites[i].enabled = visible;
        }

        foreach (var label in labels)
        {
            label.enabled = visible;
        }
    }
}
